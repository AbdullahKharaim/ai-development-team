#!/usr/bin/env python3
"""Entry point for the `/ai-team` Claude Code skill: prepare, launch and observe team tasks.

    python3 live/team.py prepare SLUG          -> creates a staging directory, prints its path
    python3 live/team.py start STAGING_DIR     -> validates, installs project + hidden acceptance
                                                  tests, runs readiness, launches `aidev run-live`
                                                  DETACHED, prints the task id
    python3 live/team.py status [TASK_ID]      -> read-only status (latest task if omitted)
    python3 live/team.py list                  -> read-only status of all team tasks

This is a thin wrapper around the existing orchestrator; it adds no new agent logic.
Every launch goes through `aidev run-live --confirm-live`, so the owner-approved live
limits, readiness gate, model policy, sandboxes and git checks all apply unchanged.

Staging layout written by the supervising Claude session:
    STAGING/task.json            {"objective", "acceptance_criteria", optional "complexity",
                                  "max_cycles", "max_model_calls", "max_clarifications"}
    STAGING/repo/SPEC.md         specification (plus any skeleton files)
    STAGING/acceptance/acceptance_test*.py   hidden trusted acceptance tests (unittest)
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HOME = Path.home()
PROJECTS = Path(os.environ.get("AIDEV_PROJECTS", HOME / "aidev-projects"))
STAGING = PROJECTS / "_staging"
TASKS = PROJECTS / "tasks"           # launcher records + orchestrator stdout logs
RUNS = PROJECTS / "runs"             # orchestrator evidence (run dirs)
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,40}$")
TASK_KEYS = {"objective", "acceptance_criteria", "complexity", "max_cycles", "max_model_calls",
             "max_clarifications", "stage_timeout_s", "test_timeout_s", "task_timeout_s"}
GIT_ENV = {"PATH": "/usr/bin:/bin", "HOME": str(HOME), "LANG": "C.UTF-8",
           "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull}
RUNNER = '''#!/usr/bin/env python3
"""Trusted test command (generated by live/team.py): repository unit tests, then the hidden
acceptance tests in this directory. Exit 0 only if both pass."""
import os, subprocess, sys, unittest
from pathlib import Path
HERE = Path(__file__).resolve().parent
own = 0
if os.path.isdir("tests"):
    print("== repository unit tests", flush=True)
    own = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-t", ".", "-v"],
                         env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}).returncode
    print(f"== repository tests exit code {own}", flush=True)
else:
    print("== repository unit tests: none (no tests/ directory)", flush=True)
    own = 1
print("== acceptance tests", flush=True)
sys.path.insert(0, os.getcwd()); sys.path.insert(1, str(HERE)); sys.dont_write_bytecode = True
try:
    suite = unittest.defaultTestLoader.discover(str(HERE), pattern="acceptance_test*.py", top_level_dir=str(HERE))
    res = unittest.TextTestRunner(verbosity=2, stream=sys.stdout).run(suite)
    ok = res.wasSuccessful() and res.testsRun > 0
    print(f"== acceptance summary: ran={res.testsRun} failures={len(res.failures)} errors={len(res.errors)}")
except Exception as e:
    print(f"acceptance tests could not run: {type(e).__name__}: {e}"); ok = False
print(f"== acceptance {'PASSED' if ok else 'FAILED'}", flush=True)
sys.exit(0 if own == 0 and ok else 1)
'''


class TeamError(RuntimeError):
    pass


def _git(cwd: Path, *args: str) -> str:
    return subprocess.run(["/usr/bin/git", "-c", "user.name=aidev-architect",
                           "-c", "user.email=architect@localhost.invalid", "-c", "commit.gpgsign=false",
                           "-c", "init.defaultBranch=main", *args], cwd=cwd, env=GIT_ENV, check=True,
                          capture_output=True, text=True).stdout


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


# --------------------------------------------------------------------- prepare
def prepare(slug: str) -> dict:
    if not SLUG_RE.match(slug):
        raise TeamError("project name must be 2-41 chars of a-z, 0-9 and '-'")
    for p in (PROJECTS / slug, PROJECTS / f"{slug}-acceptance"):
        if p.exists():
            raise TeamError(f"{p} already exists; choose another project name")
    stage = STAGING / f"{slug}-{time.strftime('%Y%m%d-%H%M%S')}"
    (stage / "repo").mkdir(parents=True)
    (stage / "acceptance").mkdir()
    return {"staging": str(stage), "slug": slug,
            "write": {"task": str(stage / "task.json"), "spec": str(stage / "repo" / "SPEC.md"),
                      "acceptance_tests": str(stage / "acceptance") + "/acceptance_test*.py"}}


# ----------------------------------------------------------------------- start
def _validate_staging(stage: Path) -> tuple[str, dict]:
    if not (stage.is_dir() and stage.parent == STAGING):
        raise TeamError(f"{stage} is not a staging directory created by 'prepare'")
    slug = re.sub(r"-\d{8}-\d{6}$", "", stage.name)
    task = json.loads((stage / "task.json").read_text())
    extra = set(task) - TASK_KEYS
    if extra:
        raise TeamError(f"task.json has unsupported fields: {sorted(extra)}")
    if not (stage / "repo" / "SPEC.md").is_file():
        raise TeamError("repo/SPEC.md is missing")
    tests = sorted((stage / "acceptance").glob("acceptance_test*.py"))
    if not tests:
        raise TeamError("acceptance/acceptance_test*.py is missing (hidden trusted tests are required)")
    for t in tests:
        compile(t.read_text(), str(t), "exec")       # syntax check only; nothing is executed
    if any(p.name == ".git" for p in (stage / "repo").iterdir()):
        raise TeamError("repo/ must not contain a .git directory")
    return slug, task


def start(stage_dir: str, *, mock_agents: str | None = None) -> dict:
    stage = Path(stage_dir).resolve()
    slug, spec_task = _validate_staging(stage)
    repo, acc = PROJECTS / slug, PROJECTS / f"{slug}-acceptance"
    task_id = f"{slug}-{time.strftime('%Y%m%d-%H%M%S')}"
    for p in (repo, acc, RUNS / task_id, TASKS / f"{task_id}.json"):
        if p.exists():
            raise TeamError(f"{p} already exists; nothing was overwritten")
    TASKS.mkdir(parents=True, exist_ok=True)
    RUNS.mkdir(parents=True, exist_ok=True)

    shutil.copytree(stage / "repo", repo)
    shutil.copytree(stage / "acceptance", acc)
    (acc / "run_tests.py").write_text(RUNNER)
    if not (repo / ".gitignore").exists():
        (repo / ".gitignore").write_text("__pycache__/\n*.pyc\n*.db\n.venv/\n")
    _git(repo, "init", "-q")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "chore: specification and skeleton (supervising architect, /ai-team)")

    task = {"task_id": task_id, **spec_task,
            "test_command": ["python3", str(acc / "run_tests.py")]}
    task_file = TASKS / f"{task_id}.task.json"
    task_file.write_text(json.dumps(task, indent=2) + "\n")
    log = TASKS / f"{task_id}.log"

    if mock_agents:   # deterministic tests only: same orchestrator, mock/command agents
        argv = [sys.executable, "-m", "aidev", "run", "--task", str(task_file), "--repo", str(repo),
                "--runs-dir", str(RUNS), "--agents", mock_agents]
        mode = "mock"
    else:
        r = subprocess.run([sys.executable, str(ROOT / "live" / "readiness.py")], cwd=ROOT,
                           capture_output=True, text=True, timeout=600)
        if r.returncode != 0:
            raise TeamError("readiness failed; no model was started:\n" + (r.stdout + r.stderr)[-2000:])
        argv = [sys.executable, "-m", "aidev", "run-live", "--confirm-live", "--task", str(task_file),
                "--repo", str(repo), "--runs-dir", str(RUNS),
                "--readiness", str(ROOT / "live" / "readiness-report.json")]
        mode = "live"

    # Detached: the workflow must outlive the supervising session's shell call.
    with open(log, "ab") as fh:
        proc = subprocess.Popen(argv, cwd=ROOT, stdin=subprocess.DEVNULL, stdout=fh, stderr=fh,
                                start_new_session=True)
    record = {"task_id": task_id, "mode": mode, "pid": proc.pid, "started_at": _now(),
              "project": str(repo), "acceptance": str(acc), "run_dir": str(RUNS / task_id),
              "log": str(log), "argv": argv}
    (TASKS / f"{task_id}.json").write_text(json.dumps(record, indent=2) + "\n")
    shutil.rmtree(stage)
    return record


# ---------------------------------------------------------------------- status
def _alive(pid: int, task_id: str) -> bool:
    try:
        cmd = Path(f"/proc/{pid}/cmdline").read_bytes().split(b"\0")
        state = Path(f"/proc/{pid}/stat").read_text().rsplit(")", 1)[-1].split()[0]
    except OSError:
        return False
    return state != "Z" and any(task_id.encode() in c for c in cmd)


def status(task_id: str | None = None) -> dict:
    if task_id is None:
        recs = sorted(TASKS.glob("*-[0-9]*-[0-9]*.json"), key=lambda p: p.stat().st_mtime)
        recs = [p for p in recs if not p.name.endswith(".task.json")]
        if not recs:
            raise TeamError("no team tasks found")
        task_id = recs[-1].stem
    rec_path = TASKS / f"{task_id}.json"
    if not rec_path.is_file():
        raise TeamError(f"unknown task id {task_id}")
    rec = json.loads(rec_path.read_text())
    run = Path(rec["run_dir"])
    events = []
    if (run / "events.jsonl").is_file():
        events = [json.loads(l) for l in (run / "events.jsonl").read_bytes().split(b"\n") if l.strip()]
    result = json.loads((run / "result.json").read_text()) if (run / "result.json").is_file() else None
    alive = _alive(rec["pid"], task_id)
    started = [e for e in events if e["event"] == "stage_started"]
    exited = {(e["data"]["stage"], e["data"]["cycle"], e["data"].get("attempt", 1))
              for e in events if e["event"] == "stage_process_exit"}
    current = None
    if started:
        d = started[-1]["data"]
        if (d["stage"], d["cycle"], d.get("attempt", 1)) not in exited:
            current = {"stage": d["stage"], "cycle": d["cycle"], "role": d["role"], "since": started[-1]["ts"]}
    if not current and events and events[-1]["event"] == "tests_started":
        current = {"stage": "tests", "cycle": events[-1]["data"]["cycle"], "since": events[-1]["ts"]}
    if result is not None:
        phase = "FINISHED"
    elif alive:
        phase = "RUNNING"
    else:
        phase = "DIED"   # process gone without a final result: interrupted or crashed
    out = {"task_id": task_id, "phase": phase, "mode": rec["mode"], "started_at": rec["started_at"],
           "process_alive": alive, "events": len(events),
           "model_calls": sum(1 for _ in started), "review_cycles":
           sum(1 for e in events if e["event"] == "review_bound"), "current_step": current,
           "last_event": events[-1]["event"] if events else None,
           "project": rec["project"], "run_dir": rec["run_dir"], "log": rec["log"]}
    if result is not None:
        out.update(state=result["state"], success=result["success"], detail=result["detail"],
                   final_commit=result["final_commit"], duration_s=result["duration_s"],
                   model_selection=result.get("model_selection"),
                   review_findings=[f for c in result["cycles"] for f in c["review"]["findings"]],
                   report=str(run / "report.md"), task_branch=result["task_branch"],
                   base_branch_unchanged=result["base_branch_unchanged"])
    if phase == "DIED":
        out["log_tail"] = Path(rec["log"]).read_text(errors="replace")[-1500:] if Path(rec["log"]).exists() else ""
        # Agents run in their own session; if the orchestrator itself was killed they are no
        # longer supervised. Report (never kill) any process still working inside the run dir.
        out["orphan_processes"] = _processes_in(run)
    return out


def _processes_in(run_dir: Path) -> list[dict]:
    found, root = [], str(run_dir.resolve())
    for e in os.listdir("/proc"):
        if not e.isdigit():
            continue
        try:
            cwd = os.readlink(f"/proc/{e}/cwd")
            cmd = Path(f"/proc/{e}/cmdline").read_bytes().replace(b"\0", b" ").decode(errors="replace")
        except OSError:
            continue
        if cwd == root or cwd.startswith(root + "/"):
            found.append({"pid": int(e), "cwd": cwd, "cmd": cmd.strip()[:200]})
    return found


def list_all() -> list[dict]:
    ids = sorted(p.stem for p in TASKS.glob("*.json") if not p.name.endswith(".task.json"))
    return [status(i) for i in ids]


def main(argv: list[str]) -> int:
    try:
        if len(argv) >= 2 and argv[0] == "prepare":
            out = prepare(argv[1])
        elif len(argv) >= 2 and argv[0] == "start":
            mock = argv[argv.index("--mock-agents") + 1] if "--mock-agents" in argv else None
            out = start(argv[1], mock_agents=mock)
        elif argv and argv[0] == "status":
            out = status(argv[1] if len(argv) > 1 else None)
        elif argv and argv[0] == "list":
            out = list_all()
        else:
            print(__doc__)
            return 2
    except (TeamError, OSError, ValueError, subprocess.SubprocessError) as e:
        print(json.dumps({"error": str(e)}))
        return 1
    print(json.dumps(out, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
